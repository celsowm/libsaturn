#!/usr/bin/env python3
"""Build the original procedural World LOD HLOD acceptance asset."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from model_pipeline.world_hlod import build_demo_package  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path, help="generated .wlh package")
    parser.add_argument("--source", type=Path, help="generated C source embedding the package")
    parser.add_argument("--header", required=True, type=Path, help="generated C build metadata")
    parser.add_argument("--report", required=True, type=Path, help="generated JSON metrics")
    args = parser.parse_args()

    package, report = build_demo_package()
    max_local = max(
        (abs(round(v * 65536.0)) for cell in report["cells"]
         for v in cell["aabb_local"]), default=0
    )
    if len(package) != report["package_bytes"]:
        raise SystemExit("internal HLOD byte-accounting mismatch")
    for path in (args.output, args.header, args.report, args.source):
        if path is None:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(package)
    max_vertices = max(level["vertices"] for cell in report["cells"]
                       for level in cell["levels"])
    max_faces = max(level["faces"] for cell in report["cells"]
                    for level in cell["levels"])
    args.header.write_text(
        "/* Generated by tools/build_world_hlod_demo.py; do not edit. */\n"
        "#ifndef WORLD_LOD3D_DEMO_HLOD_H\n"
        "#define WORLD_LOD3D_DEMO_HLOD_H\n"
        "#include <stdint.h>\n"
        f"#define SAT_WORLD_HLOD_DEMO_PACKAGE_BYTES {len(package)}u\n"
        f"#define SAT_WORLD_HLOD_DEMO_CELL_COUNT {report['cell_count']}u\n"
        f"#define SAT_WORLD_HLOD_DEMO_MAX_VERTICES {max_vertices}u\n"
        f"#define SAT_WORLD_HLOD_DEMO_MAX_FACES {max_faces}u\n"
        f"#define SAT_WORLD_HLOD_DEMO_MAX_LOCAL_COORD_FX16 {max_local}LL\n"
        f"#define SAT_WORLD_HLOD_DEMO_SOURCE_SHA256 \"{report['source_sha256']}\"\n"
        "extern const uint8_t g_world_hlod_demo_package[];\n"
        "extern const uint32_t g_world_hlod_demo_package_size;\n"
        "#endif\n",
        encoding="ascii",
        newline="\n",
    )
    if args.source:
        rows = [package[i:i + 16] for i in range(0, len(package), 16)]
        body = ",\n".join("    " + ", ".join(f"0x{byte:02x}u" for byte in row)
                             for row in rows)
        args.source.write_text(
            "/* Generated by tools/build_world_hlod_demo.py; do not edit. */\n"
            "#include \"world_lod3d_demo_hlod.h\"\n"
            "const uint8_t g_world_hlod_demo_package[] = {\n"
            f"{body}\n"
            "};\n"
            f"const uint32_t g_world_hlod_demo_package_size = {len(package)}u;\n",
            encoding="ascii", newline="\n",
        )
    args.report.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n",
                           encoding="utf-8", newline="\n")
    print(f"WLOD1: {report['cell_count']} cells, {len(package)} exact bytes, "
          f"SHA-256 {report['source_sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
