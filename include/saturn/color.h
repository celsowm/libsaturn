#ifndef SATURN_COLOR_H
#define SATURN_COLOR_H

#include <stdint.h>

/* ------------------------------------------------------------------ */
/* Named RGB555 colors                                                 */
/* ------------------------------------------------------------------ */
#define SAT_COLOR_BLACK   ((uint16_t)0x0000)
#define SAT_COLOR_BLUE    ((uint16_t)0x001F)
#define SAT_COLOR_GREEN   ((uint16_t)0x03E0)
#define SAT_COLOR_RED     ((uint16_t)0x7C00)
#define SAT_COLOR_YELLOW  ((uint16_t)0x7FE0)
#define SAT_COLOR_MAGENTA ((uint16_t)0x7C1F)
#define SAT_COLOR_CYAN    ((uint16_t)0x03FF)
#define SAT_COLOR_WHITE   ((uint16_t)0x7FFF)
#define SAT_COLOR_ORANGE  ((uint16_t)0x7E00)
#define SAT_COLOR_VIOLET  ((uint16_t)0x401F)
#define SAT_COLOR_GRAY    ((uint16_t)0x4208)
#define SAT_COLOR_TEAL    ((uint16_t)0x0210)
#define SAT_COLOR_OLIVE   ((uint16_t)0x4210)
#define SAT_COLOR_BROWN   ((uint16_t)0x5810)

#endif /* SATURN_COLOR_H */
