#ifndef SATURN_CHARACTER_ASSET_FORMAT_H
#define SATURN_CHARACTER_ASSET_FORMAT_H
/* SKA1 wire sizes are fixed, independent of native pointer sizes and padding.
 * tools/model_pipeline/skeletal_binary.py writes this versioned format. */
enum {
    SAT_CHARACTER_ARCHIVE_MAGIC = 0x534b4131u,
    SAT_CHARACTER_ARCHIVE_VERSION = 1u,
    SAT_CHARACTER_HEADER_WORDS = 24u,
    SAT_CHARACTER_HEADER_BYTES = SAT_CHARACTER_HEADER_WORDS * 4u,
    SAT_CHARACTER_JOINT_BYTES = 36u,
    SAT_CHARACTER_RIGID_BYTES = 8u,
    SAT_CHARACTER_BLEND_BYTES = 26u,
    SAT_CHARACTER_VERTEX_BYTES = 12u,
    SAT_CHARACTER_FACE_BYTES = 8u,
    SAT_CHARACTER_TEXTURE_BYTES = 16u,
    SAT_CHARACTER_PALETTE_BYTES = 256u * 2u,
    SAT_CHARACTER_CLIP_BYTES = 24u,
    SAT_CHARACTER_POSE_BYTES = 3u * 4u + 4u * 2u,
    SAT_CHARACTER_EVENT_BYTES = 4u
};
enum sat_character_archive_field {
    SAT_CHAR_MAGIC, SAT_CHAR_VERSION, SAT_CHAR_SIZE, SAT_CHAR_JOINTS,
    SAT_CHAR_RIGID, SAT_CHAR_BLEND, SAT_CHAR_VERTICES, SAT_CHAR_FACES,
    SAT_CHAR_TEXTURES, SAT_CHAR_PALETTES, SAT_CHAR_CLIPS, SAT_CHAR_POS_SHIFT,
    SAT_CHAR_MAX_JOINT, SAT_CHAR_JOINT_OFFSET, SAT_CHAR_RIGID_OFFSET,
    SAT_CHAR_BLEND_OFFSET, SAT_CHAR_VERTEX_OFFSET, SAT_CHAR_FACE_OFFSET,
    SAT_CHAR_SELECTOR_OFFSET, SAT_CHAR_TEXTURE_OFFSET, SAT_CHAR_PALETTE_OFFSET,
    SAT_CHAR_CLIP_OFFSET, SAT_CHAR_NAME_OFFSET, SAT_CHAR_BOUNDS_OFFSET
};
/* Directory fields; explicit wire offsets, not native pointer-containing
 * descriptor offsets. Keep payload layout decisions in this one header. */
enum {
    SAT_CHAR_TEXTURE_PAYLOAD=0,
    SAT_CHAR_TEXTURE_WIDTH=4,
    SAT_CHAR_TEXTURE_HEIGHT=6,
    SAT_CHAR_TEXTURE_FLAGS=8,
    SAT_CHAR_TEXTURE_PALETTE_BASE=10,
    SAT_CHAR_TEXTURE_PIXEL_COUNT=12,
    SAT_CHAR_CLIP_POSES=0,
    SAT_CHAR_CLIP_EVENTS=4,
    SAT_CHAR_CLIP_NAME=8,
    SAT_CHAR_CLIP_FRAME_COUNT=12,
    SAT_CHAR_CLIP_JOINT_COUNT=14,
    SAT_CHAR_CLIP_EVENT_COUNT=16,
    SAT_CHAR_CLIP_RATE_NUM=18,
    SAT_CHAR_CLIP_RATE_DEN=20,
    SAT_CHAR_CLIP_FLAGS=22,
    SAT_CHAR_TABLE_COUNT=(int)SAT_CHARACTER_HEADER_WORDS-(int)SAT_CHAR_JOINT_OFFSET,
    SAT_CHARACTER_MAX_JOINTS=255,
    SAT_CHARACTER_MAX_POS_SHIFT=15
};
#endif
